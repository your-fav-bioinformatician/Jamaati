const strings = { en, ar };

export const stringsFor = (lang) => strings[lang] ?? strings[DEFAULT_LANG];

export const dirFor = (lang) => (lang === 'ar' ? 'rtl' : 'ltr');

/** Replaces `{name}` placeholders, e.g. fill('Rank {n}', { n: 3 }). */
export const fill = (template, values) =>
  template.replace(/\{(\w+)\}/g, (m, key) => (key in values ? String(values[key]) : m));

/** The localized question text if we have one for this id, else the server's text. */
export const translateQuestion = (s, id, fallback) => s.quiz.questionTranslations[id] ?? fallback;
